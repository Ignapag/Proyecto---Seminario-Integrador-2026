-- Matrices de acceso versionadas. No modifica usuarios ni credenciales.
CREATE TABLE rol_acceso (
    rol TEXT PRIMARY KEY CHECK (rol IN ('ADMINISTRADOR', 'DUENIO', 'EMPLEADO', 'REPARTIDOR', 'CLIENTE')),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0)
);

CREATE TABLE rol_permiso (
    rol TEXT NOT NULL REFERENCES rol_acceso(rol),
    permiso TEXT NOT NULL CHECK (permiso IN (
        'auditoria.ver',
        'caja.aprobar',
        'caja.generar',
        'caja.ver',
        'clientes.ver',
        'delivery.corregir',
        'delivery.operar',
        'delivery.planificar',
        'delivery.ver',
        'pagos.conciliar',
        'pagos.corregir',
        'pagos.registrar',
        'pagos.ver',
        'pedidos.cambiar_estado',
        'pedidos.crear',
        'pedidos.editar',
        'pedidos.recuperar',
        'pedidos.ver',
        'productos.gestionar',
        'productos.ver_receta',
        'reportes.financieros',
        'reportes.ver',
        'stock.gestionar',
        'stock.reponer',
        'stock.ver',
        'usuarios.administrar_permisos',
        'usuarios.asignar_roles',
        'usuarios.gestionar',
        'usuarios.ver',
        'whatsapp.gestionar',
        'whatsapp.gestionar_notificaciones',
        'whatsapp.ver',
        'whatsapp.ver_notificaciones'
    )),
    PRIMARY KEY (rol, permiso)
);

